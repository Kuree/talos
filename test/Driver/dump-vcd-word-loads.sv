// IEEE 1800-2023 21.7.2: each value change of a traced variable is one
// record. The writer loads values of up to 64 bits as words where the state
// planes have room past them: odd-width unpacked elements (m, 3 bits; big, 63
// bits), a value with X and Z bits (x6), and a 32-bit integer, with a wide
// variable (pad) after them. The records are those the writer printed before
// it formatted records in place.
module top;
  logic clk = 0;
  logic [2:0] m [0:9];
  logic [62:0] big [0:3];
  logic [5:0] x6 = 6'b01xz10;
  logic [255:0] pad = 0;
  integer k;
  always #5 clk = ~clk;
  initial begin
    for (k = 0; k < 10; k++) m[k] = 3'(k);
    for (k = 0; k < 4; k++) big[k] = {k[2:0], 60'h0f0f0f0f0f0f0f0} ^ 63'(k * 7);
  end
  always @(posedge clk) begin
    for (k = 0; k < 10; k++) m[k] <= m[k] + 3'(k + 1);
    big[1] <= {big[1][61:0], big[1][62]};
    big[3] <= ~big[3];
    x6 <= {x6[4:0], x6[5]};
    pad[255] <= ~pad[255];
  end
  initial begin
    $dumpfile("u.vcd");
    $dumpvars(0, top);
    // Keep the declaration IDs used by this record-by-record packing test.
    $dumpflush;
    #32 $finish;
  end
endmodule

